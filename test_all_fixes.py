"""
Комплексный тест всех исправлений валидации
Проверяет 6 критических багов которые были исправлены
"""
import sys
sys.path.insert(0, "d:\\TestProject")

# Отключаем LanguageTool для скорости
import check_catalog
check_catalog._LT = None

from check_catalog import (
    normalize_compound_capitalization,
    ensure_category_format,
    normalize_other_pattern,
    check_spelling,
)

print("=" * 80)
print("КОМПЛЕКСНЫЙ ТЕСТ ВСЕХ ИСПРАВЛЕНИЙ")
print("=" * 80)

# Счетчики
total_tests = 0
passed_tests = 0
failed_tests = 0

def test_case(name, actual, expected, description=""):
    """Проверка одного тест-кейса"""
    global total_tests, passed_tests, failed_tests
    total_tests += 1

    passed = actual == expected
    if passed:
        passed_tests += 1
        status = "✅ PASS"
    else:
        failed_tests += 1
        status = "❌ FAIL"

    print(f"\n{status} | {name}")
    if description:
        print(f"  Описание: {description}")
    print(f"  Ожидалось: {expected}")
    print(f"  Получено:  {actual}")

    return passed

# ============================================================================
# ТЕСТ 1: Капитализация одного слова
# ============================================================================
print("\n" + "=" * 80)
print("ТЕСТ 1: Капитализация одного слова (игрушки → Игрушки)")
print("=" * 80)

test_case(
    "Одно слово lowercase",
    normalize_compound_capitalization("игрушки"),
    "Игрушки",
    "Простое слово должно стать с заглавной буквы"
)

test_case(
    "Категория формат",
    ensure_category_format("игрушки"),
    None,  # Уже правильная форма (nomn + plur), только капитализация нужна
    "игрушки уже во множ. числе, только капитализация"
)

# ============================================================================
# ТЕСТ 2: Конструкции с родительным падежом (НЕ ТРОГАЕМ!)
# ============================================================================
print("\n" + "=" * 80)
print("ТЕСТ 2: Детские наборы кассира (генитив - НЕ МЕНЯЕМ)")
print("=" * 80)

result = ensure_category_format("Детские наборы кассира")
test_case(
    "Детские наборы кассира",
    result,
    None,  # Не должно быть исправлений (кассира - родительный падеж)
    "Генитивный модификатор - только капитализация, форму не трогаем"
)

result = ensure_category_format("наборы кассира")
test_case(
    "наборы кассира (lowercase)",
    result[1] if result else None,
    "Наборы кассира",  # Только капитализация
    "Генитив сохраняется, только капитализация"
)

# ============================================================================
# ТЕСТ 3: Паттерн "Другой" с сингуляризацией
# ============================================================================
print("\n" + "=" * 80)
print("ТЕСТ 3: Другой/Другая + параметр (род + сингуляризация)")
print("=" * 80)

test_case(
    "Другой марка машинки → Другая марка машинки",
    normalize_other_pattern("марка машинки", "Другой марка машинки")[1] if normalize_other_pattern("марка машинки", "Другой марка машинки") else None,
    "Другая марка машинки",
    "Женский род (марка) + машинки в генитиве остается"
)

test_case(
    "Другая особенности → Другая особенность",
    normalize_other_pattern("особенности", "Другая особенности")[1] if normalize_other_pattern("особенности", "Другая особенности") else None,
    "Другая особенность",
    "особенности (nomn plur) → особенность (nomn sing)"
)

test_case(
    "Другой игрушечный транспорт",
    normalize_other_pattern("игрушечный транспорт", "Другой игрушечный транспорт"),
    None,  # Уже правильно
    "Мужской род, уже правильно"
)

# ============================================================================
# ТЕСТ 4: Фильтр е↔ё из LanguageTool
# ============================================================================
print("\n" + "=" * 80)
print("ТЕСТ 4: Фильтр е↔ё замен (оба варианта допустимы)")
print("=" * 80)

# Симулируем - check_spelling должен игнорировать е↔ё
# Но у нас _LT = None, так что просто проверим логику
test_case(
    "е↔ё фильтр логика",
    "вертолеты".replace('е', 'ё').replace('Е', 'Ё') == "вертолёты".replace('е', 'ё').replace('Е', 'Ё'),
    True,
    "Проверка что е↔ё детектится правильно"
)

# ============================================================================
# ТЕСТ 5: Неисчисляемые существительные
# ============================================================================
print("\n" + "=" * 80)
print("ТЕСТ 5: Неисчисляемые существительные (транспорт)")
print("=" * 80)

result = ensure_category_format("Игрушечный транспорт")
test_case(
    "Игрушечный транспорт",
    result,
    None,  # транспорт в списке _CATEGORY_MASS_LIKE, не меняем
    "транспорт неисчисляемое, не преобразуем во множ. число"
)

result = ensure_category_format("игрушечный транспорт")
test_case(
    "игрушечный транспорт (lowercase)",
    result[1] if result else None,
    "Игрушечный транспорт",  # Только капитализация
    "Неисчисляемое + капитализация"
)

# ============================================================================
# ТЕСТ 6: Капитализация составных фраз
# ============================================================================
print("\n" + "=" * 80)
print("ТЕСТ 6: Капитализация составных фраз")
print("=" * 80)

test_case(
    "Другой Красный Цвет",
    normalize_compound_capitalization("Другой Красный Цвет"),
    "Другой красный цвет",
    "Первое слово заглавное, остальные строчные"
)

test_case(
    "Игрушки-Роботы",
    normalize_compound_capitalization("Игрушки-Роботы"),
    "Игрушки-роботы",
    "Через дефис: первое заглавное, второе строчное"
)

test_case(
    "Другой iPhone (бренд)",
    normalize_compound_capitalization("Другой iPhone"),
    "Другой iPhone",
    "iPhone - бренд с латиницей, сохраняется как есть"
)

test_case(
    "Другая USB мышь",
    normalize_compound_capitalization("Другая USB мышь"),
    "Другая USB мышь",
    "USB - аббревиатура, сохраняется"
)

# ============================================================================
# ИТОГИ
# ============================================================================
print("\n" + "=" * 80)
print("ИТОГИ ТЕСТИРОВАНИЯ")
print("=" * 80)
print(f"Всего тестов:  {total_tests}")
print(f"Пройдено:      {passed_tests} ✅")
print(f"Провалено:     {failed_tests} ❌")
print(f"Процент:       {(passed_tests/total_tests*100):.1f}%")
print("=" * 80)

